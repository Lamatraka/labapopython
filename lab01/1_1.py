surname = input('Введите фамилию: ')
name = input('Введите имя: ')
gr = input('Введите группу: ')
city = input('Введите город: ')

while True:
    age = int(input('Введите полное количество лет: '))
    if 1 <= age <= 120:
        break
    print('Возраст должен быть от 1 до 120')

pr = input('Введите любимый предмет: ')

while True:
    hr = float(input('Введите количество часов подготовки в неделю: '))
    if hr >= 0:
        break
    print('Часы должны быть неотрицательным числом')

hrp = hr / 7

print('Карточка студента')
print('Имя, фамилия: ' + name + ' ' + surname)
print('Группа: ' + gr)
print('Город: ' + city)
print('Возраст через 4 года: ' + str(age + 4))
print('Любимый предмет: ' + pr)
print(f'Время подготовки за 4 недели: {hr * 4:.2f}')
print(f'Среднее время подготовки в день: {hrp:.2f}')